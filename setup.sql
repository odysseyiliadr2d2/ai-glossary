-- 다시 실행해도 안전하다(기존 집계는 유지된다). 용어를 추가한 뒤 다시 실행하면 새 용어도 집계 대상이 된다.

create table if not exists public.term_hits (
  term_id    text primary key,
  hits       bigint      not null default 0,
  updated_at timestamptz not null default now()
);

-- 누구나 순위를 읽을 수 있지만, 표를 직접 고칠 수는 없다
alter table public.term_hits enable row level security;
drop policy if exists "public read" on public.term_hits;
create policy "public read" on public.term_hits for select to anon, authenticated using (true);
revoke insert, update, delete on public.term_hits from anon, authenticated;
grant select on public.term_hits to anon, authenticated;

-- 조회 1회를 더하는 함수. 등록된 용어 id만 올라가고 새 행은 만들지 않는다
create or replace function public.increment_hit(p_term text)
returns void
language sql
security definer
set search_path = public
as $$
  update public.term_hits
     set hits = hits + 1, updated_at = now()
   where term_id = p_term;
$$;
revoke all on function public.increment_hit(text) from public;
grant execute on function public.increment_hit(text) to anon, authenticated;

